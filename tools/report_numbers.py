"""Writes eval/numbers.md: every number the report and the READMEs cite, computed from the result files, one fact
per line, in the wording the report uses. tools/check_claims.py checks the report against this file and the
analysis tables with evidence-check, so a number in the report must come out of a result file.

    python tools/report_numbers.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from lak.agent import MAX_ROUNDS  # noqa: E402
from lak.rca import ORDER  # noqa: E402
from lak.task import get_task, read_jsonl  # noqa: E402

RES = ROOT / "results"


def load(p: Path):
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


def f3(x):
    return f"{x:.3f}"


def ci(c):
    return f"[{c[0]:.2f}–{c[1]:.2f}]"


def sci(c):
    return f"[{c[0]:+.3f}, {c[1]:+.3f}]"


def signed(x):
    return f"{x:+.3f}"


def verdict(v):
    return {"B better": "better", "B worse": "worse"}.get(v, v)


def main() -> int:
    L: list[str] = ["# Numbers cited in the report", "",
                    "Generated by `tools/report_numbers.py` from the result files; do not edit by hand.", ""]

    # ---- structure
    ad, asap = get_task("ad_policy"), get_task("asap")
    skills = sorted(p.name for p in (ROOT / "skills").iterdir() if (p / "SKILL.md").exists())
    tasks = sorted(p.name for p in (ROOT / "tasks").iterdir() if (p / "task.json").exists())
    main_exp = load(ROOT / "experiments" / "main.json")
    v1_arms = list(dict.fromkeys(a["arm"] for r in main_exp["runs"] for a in r["arms"] if "id" not in a))
    lang_counts = {}
    for it in ad.items("dev") + ad.items("test_a") + ad.items("test_b"):
        lang_counts.setdefault(ad.rule_lang(it), len(ad.labels_for(it)))
    per_lang = "/".join(sorted({str(v) for v in lang_counts.values()}))
    groups = list(dict.fromkeys(l.split("#")[0] for l in asap.all_labels))
    rca_rows = [r for f in sorted((RES / "main" / "rca").glob("*.json")) if not f.name.endswith(".zh.json")
                for r in load(f)["decisions"]]
    RCA_PASSES = len({k for r in rca_rows for k in r if k.startswith("pass")})
    L += ["## Structure", "",
          f"- The kit has {len(skills)} skills: {', '.join(skills)}.",
          f"- The kit runs {len(tasks)} labelling tasks: {', '.join(tasks)}.",
          f"- The experiments compare {len(v1_arms)} arms: {', '.join(v1_arms)}.",
          f"- The agent must answer after at most {MAX_ROUNDS} tool rounds (MAX_ROUNDS in lak/agent.py).",
          f"- The root-cause taxonomy has {len(ORDER)} causes: {', '.join(ORDER)}; each wrong decision is classified in {RCA_PASSES} independent passes.",
          f"- The ad-policy rulebook has {len(ad.all_labels)} labels, {per_lang} per language ({'; '.join(f'{k}: {v}' for k, v in sorted(lang_counts.items()))}); "
          f"the ASAP rulebook has {len(asap.all_labels)} labels in {len(groups)} groups ({', '.join(groups)}).",
          f"- ASAP sets: dev {len(asap.items('dev'))}, test A {len(asap.items('test_a'))}, test B {len(asap.items('test_b'))} reviews; the real case library has {len(asap.cases('real'))} reviews; "
          f"{len(asap.items('dev')) + len(asap.items('test_a')) + len(asap.items('test_b')) + len(asap.cases('real')):,} sampled reviews in all.",
          f"- Ad sets: dev {len(ad.items('dev'))}, test A {len(ad.items('test_a'))}, test B {len(ad.items('test_b'))} ads; {len(ad.cases('synthetic'))} synthetic ads in the case library.", ""]

    # ---- data
    syn = load(ROOT / "tasks" / "asap" / "synth_report.json")
    acc = load(RES / "acceptance.json")
    L += ["## Data", ""]
    if syn:
        r = syn["rejected"]
        L.append(f"- Synthetic reviews: {syn['generated']} were generated (USD {syn['cost_usd']:.4f}); checked in spec order until {syn['kept']} had passed, "
                 f"the filters removed {sum(r.values())} ({r.get('strong cue of an aspect outside the spec', 0)} strong cue of an aspect outside the spec, "
                 f"{r.get('language or length', 0)} language or length, {r.get('evidence missing or not verbatim', 0)} quote not verbatim); those {syn['kept']} form the library.")
    if acc:
        for f in acc["files"]:
            for c in f["checks"]:
                if c["code"] in ("A8", "A10") and (not c["passed"] or c["code"] == "A10"):
                    L.append(f"- Acceptance {c['code']}, {f['task']} {f['set']}: {c['detail']}.")
    L.append("")

    # ---- development
    L += ["## Development", ""]
    for name in ("dev1", "dev2"):
        ft = RES / name / "FIRST_TURN.md"
        if ft.exists():
            for line in ft.read_text(encoding="utf-8").splitlines():
                if line.startswith("| asap | agent |") or line.startswith("| asap | agent-cases |"):
                    cells = [c.strip() for c in line.strip("|").split("|")]
                    if len(cells) == 5 and " of " in cells[3]:          # the first table only
                        L.append(f"- {name}, ASAP, `{cells[1]}`: the first turn called a tool on {cells[3]} reviews.")
    d2 = load(RES / "dev2" / "analysis.json")
    if d2:
        for c in d2["comparisons"]:
            if c["id"] in ("d-ad-e", "d-asap-e"):
                L.append(f"- dev2 effort medium against low, {c['task']}: micro F1 {signed(c['result']['micro_f1']['diff'])}.")
        for t, sets in d2["tasks"].items():
            for arm in ("prompt-short", "prompt-rules", "agent", "agent-cases", "agent-cases-check"):
                u = sets["dev"][arm]
                L.append(f"- dev2, {t} ({u['metrics']['n_items']} items), `{arm}`: micro F1 {f3(u['metrics']['micro']['f1'])}.")
    L.append("")

    # ---- main
    an = load(RES / "main" / "analysis.json")
    if an:
        L += ["## Test A", ""]
        for t, sets in an["tasks"].items():
            for arm, u in sets["test_a"].items():
                m, o = u["metrics"], u["ops"]
                L.append(f"- {t} test A ({m['n_items']} items), `{arm}`: micro F1 {f3(m['micro']['f1'])} {ci(m['micro']['f1_ci'])}, "
                         f"USD {1000 * o['cost_per_item_usd']:.2f} per 1,000 items.")
        for c in an["comparisons"]:
            r = c["result"]
            L.append(f"- {c['id']} ({c['task']}, `{c['a']}` → `{c['b']}`): {signed(r['micro_f1']['diff'])} {sci(r['micro_f1']['diff_ci'])}, {verdict(c['verdict'])}.")
        ads = an["tasks"]["ad_policy"]["test_a"]
        for arm in ("prompt-short", "agent-cases-check"):
            la = next(s for g in ads[arm]["slices"]["groups"] if g["field"] == "meta.difficulty" for s in g["slices"] if s["value"] == "look-alike")
            L.append(f"- Ads, `{arm}`: gave a label to {la['false_alarm']['k']} of {la['false_alarm']['n']} look-alike ads.")
        for t, unit_name in (("asap", "reviews"), ("ad_policy", "ads")):
            u = an["tasks"][t]["test_a"]
            o = u["agent-cases-check"]["ops"]
            L.append(f"- {t}, `agent-cases-check`: the rule gate fired on {o['rule_gate_fired']} of {o['items']} {unit_name}; the self-check changed "
                     f"{o['check_changed_items']} of {o['check_items']} {unit_name} (+{o['check_added_labels']} / −{o['check_dropped_labels']} labels); "
                     f"exact quotes {o['evidence_exact']['k']} of {o['evidence_exact']['n']}.")
            ps = u["prompt-short"]["ops"]
            L.append(f"- {t}, `prompt-short`: exact quotes {ps['evidence_exact']['k']} of {ps['evidence_exact']['n']}.")
            ac = u["agent-cases"]["ops"]["items_using_tool"]
            L.append(f"- {t}, `agent-cases`: search_cases called on {100 * ac.get('search_cases', 0):.0f}% of {unit_name}.")
        best = an["tasks"]["asap"]["test_a"]["agent-cases-check"]
        for g in best["slices"]["groups"]:
            for s in g["slices"]:
                if s["verdict"] in ("worse", "better"):
                    L.append(f"- ASAP best arm, slice {s['value']} ({g['field']}): {signed(s['diff'])} against the rest, {s['verdict']}.")
        per = {r["label"]: r for r in best["metrics"]["per_label"]}
        for lab, key in (("Location#Downtown", "recall"), ("Food#Appearance", "recall"), ("Price#Cost_effective", "precision")):
            L.append(f"- ASAP best arm, {lab}: {key} {100 * per[lab][key]:.1f}%.")
        pair = next((p for p in best["confusion"]["top_pairs"] if p["gold"] == "Price#Level" and p["predicted"] == "Price#Cost_effective"), None)
        if pair:
            L.append(f"- ASAP best arm: Price#Level confused with Price#Cost_effective {pair['count']} times.")
        L.append("")

    # ---- root causes
    L += ["## Root causes", ""]
    for t in ("ad_policy", "asap"):
        r = load(RES / "main" / "rca" / f"{t}-test_a-agent-cases-check.json")
        if not r:
            continue
        s = r["summary"]
        L.append(f"- {t}: {s['decisions']} wrong label decisions on {s['items_with_failures']} items; both passes agree on {s['agreement']['k']} of {s['agreement']['n']}; "
                 f"{s['stable_errors']} were also wrong in every other arm.")
        L.append(f"- {t} causes: " + ", ".join(f"{k} {s['by_cause'].get(k, 0)}" for k in ORDER + ["split"]) + ".")
        if t == "asap":
            from collections import Counter
            pairs = Counter(tuple(sorted([str((d.get("pass1") or {}).get("cause")), str((d.get("pass2") or {}).get("cause"))])) for d in r["decisions"] if not d["agreed"])
            la = sum(n for (a, b), n in pairs.items() if "label_ambiguity" in (a, b) and {a, b} & {"rule_conflict", "prompt_defect", "model_capability"})
            L.append(f"- asap split decisions: in {la} of {sum(pairs.values())} one pass said label_ambiguity and the other a fixable cause "
                     f"(rule conflict {pairs.get(('label_ambiguity', 'rule_conflict'), 0)}, prompt defect {pairs.get(('label_ambiguity', 'prompt_defect'), 0)}, "
                     f"model capability {pairs.get(('label_ambiguity', 'model_capability'), 0)}).")
            rc = s["by_label"]
            L.append("- asap rule conflicts by label: " + ", ".join(f"{lab} {c.get('rule_conflict', 0)}" for lab, c in rc.items() if c.get("rule_conflict")) + ".")
    L.append("")

    # ---- revision
    rev = load(RES / "revision" / "analysis.json")
    if rev:
        L += ["## Revision", ""]
        for t, sets in rev["tasks"].items():
            for set_name, arms in sets.items():
                for arm, u in arms.items():
                    m = u["metrics"]
                    L.append(f"- {t} {set_name} ({m['n_items']} items), `{arm}`: micro F1 {f3(m['micro']['f1'])} {ci(m['micro']['f1_ci'])}, "
                             f"macro F1 {f3(m['macro']['f1'])}, USD {1000 * u['ops']['cost_per_item_usd']:.2f} per 1,000 items.")
        for c in rev["comparisons"]:
            r = c["result"]
            e = r["exact_match"]
            L.append(f"- {c['id']} ({c['task']} {c['set']}): micro F1 {signed(r['micro_f1']['diff'])} {sci(r['micro_f1']['diff_ci'])}, "
                     f"macro F1 {signed(r['macro_f1']['diff'])} {sci(r['macro_f1']['diff_ci'])}, {verdict(c['verdict'])}; "
                     f"only v2 exact on {e['b_only_right']}, only v1 on {e['a_only_right']}.")
            big = [x for x in r["per_label"] if x["diff"] is not None and abs(x["diff"]) >= 0.05]
            if big:
                L.append(f"- {c['id']} per-label F1 changes of 0.05 or more: " + ", ".join(f"{x['label']} {signed(x['diff'])}" for x in big) + ".")
        L.append("")

    # ---- costs
    cost = load(RES / "costs.json")
    if cost:
        L += ["## Costs", ""]
        for r in cost["runs"]:
            L.append(f"- {r['run']}: USD {r['cost_usd']:.4f} for {r['answers']:,} answers.")
        L.append(f"- All model calls: USD {cost['total_usd']:.2f} (USD {cost['total_usd']:.4f}).")
        L.append("")
    (ROOT / "eval" / "numbers.md").write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")
    sys.stdout.reconfigure(encoding="utf-8")
    print(f"eval/numbers.md: {sum(1 for x in L if x.startswith('- '))} facts")
    return 0


if __name__ == "__main__":
    sys.exit(main())
